import React, { useState } from 'react';
import { ChevronDown, HelpCircle } from 'lucide-react';

interface FaqItem {
  q: string;
  a: string;
}

export const FAQ: React.FC = () => {
  const [openIndex, setOpenIndex] = useState<number | null>(null);

  const faqs: FaqItem[] = [
    {
      q: 'Where can I find my downloaded ZIP file?',
      a: 'When Meta finishes preparing your Instagram data, they will send an email with a direct download button. Clicking that link downloads a .zip archive (often named instagram-username-date.zip) directly into your computer’s "Downloads" folder.'
    },
    {
      q: 'Why should I choose JSON?',
      a: 'JSON (JavaScript Object Notation) is a structured data format. FollowBack parses this raw structured data directly in your browser with 100% precision, ensuring every single follower and following relationship is accurately detected without scraping mistakes.'
    },
    {
      q: 'What happens if I select HTML?',
      a: 'HTML format generates visual web pages meant for human eyes rather than programmatic parsing. FollowBack does not support HTML exports in this version. If you upload an HTML export, you will be prompted to request your data again in JSON format.'
    },
    {
      q: 'Can I upload an old Instagram export?',
      a: 'Yes! You can upload an older export, but keep in mind the results will reflect your follower and following status at the exact date and time that archive was generated by Instagram.'
    },
    {
      q: 'Is my Instagram password required?',
      a: 'Never. FollowBack never asks for your password, phone number, login verification, or authentication cookies. It only processes the exported file you provide, completely inside your browser.'
    }
  ];

  const toggle = (i: number) => {
    setOpenIndex(openIndex === i ? null : i);
  };

  return (
    <section id="faq" className="py-16 md:py-24 bg-slate-50 border-t border-slate-200/80">
      <div className="max-w-3xl mx-auto px-4 sm:px-6 lg:px-8">
        
        <div className="text-center mb-12">
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-slate-200/80 text-secondary text-xs font-bold uppercase tracking-wider mb-3">
            <HelpCircle className="w-3.5 h-3.5" />
            <span>Got Questions?</span>
          </div>
          <h2 className="text-3xl font-extrabold text-main tracking-tight mb-2">
            Frequently Asked Questions
          </h2>
          <p className="text-secondary text-sm">
            Everything you need to know about downloading data and using FollowBack.
          </p>
        </div>

        <div className="space-y-3">
          {faqs.map((faq, idx) => {
            const isOpen = openIndex === idx;
            return (
              <div
                key={idx}
                className="bg-white border border-slate-200 rounded-2xl overflow-hidden transition-all shadow-sm"
              >
                <button
                  type="button"
                  onClick={() => toggle(idx)}
                  className="w-full py-4 px-5 text-left flex items-center justify-between gap-4 font-bold text-main hover:text-primary transition-colors text-base"
                >
                  <span>{faq.q}</span>
                  <ChevronDown
                    className={`w-4 h-4 text-secondary transition-transform duration-200 flex-shrink-0 ${
                      isOpen ? 'rotate-180 text-primary' : ''
                    }`}
                  />
                </button>
                {isOpen && (
                  <div className="px-5 pb-5 pt-1 text-sm text-secondary leading-relaxed border-t border-slate-100">
                    {faq.a}
                  </div>
                )}
              </div>
            );
          })}
        </div>

      </div>
    </section>
  );
};
